# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------

def build_html(clashes, out_path, filter_predicate=None,
               project_name=None, viewpoints_dir=None,
               generated_by=None, filter_description=None,
               include_thumbnails=True, test_name_lookup=None,
               now_iso=None):
    """Write a self-contained HTML report to `out_path`.

    Args:
        clashes              - list of clash dicts (clashes.json `clashes`
                               field).
        out_path             - destination filename (`.html` extension).
        filter_predicate     - optional callable(clash_dict) -> bool. Only
                               clashes that pass are included. None means
                               include everything.
        project_name         - human-friendly project label for the header.
        viewpoints_dir       - directory containing per-clash thumbnail
                               PNGs (`<clash-id>.png`). When set AND
                               `include_thumbnails`, each clash's image is
                               embedded as a base64 data URI. Set to None
                               to skip even if thumbnails exist on disk.
        generated_by         - user name for the "Generated by:" line.
        filter_description   - human-readable description of the active
                               filter (e.g. "Mechanical only, Open + Reviewed").
        include_thumbnails   - master switch for embedding images. Off
                               makes a much smaller file (useful for
                               huge projects).
        test_name_lookup     - dict mapping `test_id` → display name. The
                               clash dict only stores the id; the name
                               lives in the global test library. Caller
                               should pass `{tid: name for ...}` from
                               `persistence.read_global_test_library`.
        now_iso              - timestamp string for the "Generated at:"
                               line. None → use the current time. Tests
                               pass a fixed value for deterministic
                               output.

    Returns the count of clashes written (after filtering).
    """
    if test_name_lookup is None:
        test_name_lookup = {}
    if now_iso is None:
        from datetime import datetime
        now_iso = datetime.utcnow().strftime("%Y-%m-%dT%H:%M:%SZ")

    filtered = []
    for c in clashes or []:
        if not isinstance(c, dict):
            continue
        if filter_predicate is not None:
            try:
                if not filter_predicate(c):
                    continue
            except Exception:
                continue
        filtered.append(c)

    counts_by_status, counts_by_trade = _compute_counts(filtered)

    body = _render_full_html(
        clashes=filtered,
        project_name=project_name,
        generated_by=generated_by,
        generated_at=now_iso,
        filter_description=filter_description,
        counts_by_status=counts_by_status,
        counts_by_trade=counts_by_trade,
        viewpoints_dir=viewpoints_dir,
        include_thumbnails=include_thumbnails,
        test_name_lookup=test_name_lookup,
    )

    out_dir = os.path.dirname(out_path)
    if out_dir and not os.path.isdir(out_dir):
        os.makedirs(out_dir)
    with codecs.open(out_path, "w", "utf-8") as f:
        f.write(body)
    return len(filtered)


# ---------------------------------------------------------------------------
# Counts
# ---------------------------------------------------------------------------

def _compute_counts(clashes):
    """Return (counts_by_status, counts_by_trade) — two dicts mapping
    bucket name → count. Statuses include all four standard values
    even when zero (so the summary section shows "Approved: 0" rather
    than omitting the bucket)."""
    counts_by_status = {'Open': 0, 'Reviewed': 0, 'Approved': 0, 'Resolved': 0}
    counts_by_trade = {}
    for c in clashes:
        status = c.get('status') or 'Open'
        counts_by_status[status] = counts_by_status.get(status, 0) + 1
        trade = c.get('assignee') or 'Unassigned'
        counts_by_trade[trade] = counts_by_trade.get(trade, 0) + 1
    return counts_by_status, counts_by_trade


