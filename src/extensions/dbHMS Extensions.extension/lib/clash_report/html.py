# -*- coding: utf-8 -*-
"""HTML summary report builder.

Self-contained HTML — single file with inline CSS and inline base64
thumbnails. The user can email it, post it to SharePoint, or print it
to PDF directly from any browser (Ctrl+P → Save as PDF). That last
trick is why this module exists: IronPython 2.7 has no maintained
pure-Python PDF library, but every browser turns HTML into PDF for
free, so we ship HTML and inherit PDF-ability.

Designed for sharing with non-Revit consumers (clients, GCs, project
managers). Same `clashes`, `filter_predicate`, `project_name`
arguments as `excel_summary.build_xlsx` so the Reports script can
dispatch to either by selecting the right module.

The HTML structure:
  * dbHMS-branded header (slate bar, "db | HMS" wordmark)
  * Run metadata (project, generated-at, applied filter)
  * Summary cards — counts by status + by trade
  * Per-clash detail blocks: thumbnail + element refs + status / trade /
    test / comments / history snippet

Pure-data — no Revit, no WPF imports. Parses cleanly in CPython 3 for
the test suite and runs the same way under IronPython 2.7 in pyRevit.
"""

