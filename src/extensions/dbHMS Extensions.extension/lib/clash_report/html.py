def _render_full_html(clashes, project_name, generated_by, generated_at,
                       filter_description, counts_by_status, counts_by_trade,
                       viewpoints_dir, include_thumbnails, test_name_lookup):
    parts = []
    parts.append(_RENDER_HEAD)
    parts.append(_render_header(project_name, generated_by, generated_at,
                                 filter_description, len(clashes)))
    parts.append(_render_summary(counts_by_status, counts_by_trade))
    parts.append('<section class="clashes">')
    if not clashes:
        parts.append('<div class="empty">No clashes match the selected filter.</div>')
    for c in clashes:
        parts.append(_render_clash(c, viewpoints_dir, include_thumbnails,
                                    test_name_lookup))
    parts.append('</section>')
    parts.append(_RENDER_FOOT)
    return ''.join(parts)


def _render_header(project_name, generated_by, generated_at,
                    filter_description, total_count):
    pieces = []
    pieces.append('<header class="dbhms-header">')
    pieces.append('  <div class="title-block">')
    pieces.append('    <div class="title">Clash Report</div>')
    pieces.append('    <div class="subtitle">{}</div>'.format(
        _esc(project_name or 'Untitled project')))
    pieces.append('  </div>')
    pieces.append('  <div class="wordmark">')
    pieces.append('    <span class="wm-blue">db</span>')
    pieces.append('    <span class="wm-divider"> | </span>')
    pieces.append('    <span class="wm-blue">HMS</span>')
    pieces.append('  </div>')
    pieces.append('</header>')
    pieces.append('<section class="metadata">')
    pieces.append('  <div><strong>Total clashes:</strong> {}</div>'.format(
        total_count))
    if filter_description:
        pieces.append('  <div><strong>Filter:</strong> {}</div>'.format(
            _esc(filter_description)))
    pieces.append('  <div><strong>Generated:</strong> {}</div>'.format(
        _esc(generated_at)))
    if generated_by:
        pieces.append('  <div><strong>By:</strong> {}</div>'.format(
            _esc(generated_by)))
    pieces.append('</section>')
    return '\n'.join(pieces) + '\n'


def _render_summary(counts_by_status, counts_by_trade):
    pieces = []
    pieces.append('<section class="summary">')
    pieces.append('  <div class="summary-block">')
    pieces.append('    <h2>By status</h2>')
    pieces.append('    <ul class="summary-list">')
    for status in ('Open', 'Reviewed', 'Approved', 'Resolved'):
        n = counts_by_status.get(status, 0)
        color = _STATUS_COLORS.get(status, '#A0AEC0')
        pieces.append(
            '      <li><span class="dot" style="background:{};"></span>'
            '<span class="label">{}</span><span class="count">{}</span></li>'
            .format(color, _esc(status), n))
    pieces.append('    </ul>')
    pieces.append('  </div>')
    pieces.append('  <div class="summary-block">')
    pieces.append('    <h2>By trade</h2>')
    pieces.append('    <ul class="summary-list">')
    # Sorted descending by count for readability.
    items = sorted(counts_by_trade.items(), key=lambda kv: -kv[1])
    if not items:
        pieces.append('      <li class="empty-list">(no clashes)</li>')
    for trade, n in items:
        bg, fg = _TRADE_COLORS.get(trade, (_TRADE_DEFAULT_BG, _TRADE_DEFAULT_FG))
        pieces.append(
            '      <li><span class="trade-pill" style="background:{};color:{};">'
            '{}</span><span class="count">{}</span></li>'
            .format(bg, fg, _esc(trade), n))
    pieces.append('    </ul>')
    pieces.append('  </div>')
    pieces.append('</section>')
    return '\n'.join(pieces) + '\n'


def _render_clash(clash, viewpoints_dir, include_thumbnails, test_name_lookup):
    seq = clash.get('seq') or '?'
    status = clash.get('status') or 'Open'
    trade = clash.get('assignee') or 'Unassigned'
    test_id = clash.get('test_id')
    test_name = test_name_lookup.get(test_id) or '(unknown test)'
    ref_a = clash.get('ref_a') or {}
    ref_b = clash.get('ref_b') or {}
    comments = clash.get('comments') or []
    history = clash.get('history') or []
    kind = (clash.get('kind') or 'hard').lower()

    status_color = _STATUS_COLORS.get(status, '#A0AEC0')
    trade_bg, trade_fg = _TRADE_COLORS.get(
        trade, (_TRADE_DEFAULT_BG, _TRADE_DEFAULT_FG))

    img_html = ''
    if include_thumbnails and viewpoints_dir:
        img_data_uri = _read_thumbnail_data_uri(
            clash.get('id'), viewpoints_dir)
        if img_data_uri:
            img_html = (
                '<div class="clash-thumb">'
                '<img alt="Clash #{} viewpoint" src="{}"/></div>'.format(
                    _esc(seq), img_data_uri))

    pieces = []
    pieces.append('<article class="clash">')
    pieces.append('  <div class="clash-head">')
    pieces.append(
        '    <span class="clash-num">Clash #{}</span>'
        '    <span class="status-pill" style="background:{};">{}</span>'
        '    <span class="trade-pill" style="background:{};color:{};">{}</span>'
        '    <span class="kind">{}</span>'.format(
            _esc(seq), status_color, _esc(status),
            trade_bg, trade_fg, _esc(trade), _esc(kind.upper())))
    pieces.append('  </div>')
    pieces.append('  <div class="clash-body">')
    if img_html:
        pieces.append('    ' + img_html)
    pieces.append('    <div class="clash-meta">')
    pieces.append('      <div class="test-name">{}</div>'.format(_esc(test_name)))
    pieces.append('      <div class="elem-row"><span class="elem-label">A:</span> {}</div>'.format(
        _esc(ref_a.get('name') or 'unnamed')))
    pieces.append('      <div class="elem-id mono">id {} {}</div>'.format(
        _esc(ref_a.get('element_id') or '?'),
        _esc('— ' + (ref_a.get('source') or 'host'))))
    pieces.append('      <div class="elem-row"><span class="elem-label">B:</span> {}</div>'.format(
        _esc(ref_b.get('name') or 'unnamed')))
    pieces.append('      <div class="elem-id mono">id {} {}</div>'.format(
        _esc(ref_b.get('element_id') or '?'),
        _esc('— ' + (ref_b.get('source') or 'host'))))
    pieces.append('    </div>')
    pieces.append('  </div>')

    if comments:
        pieces.append('  <div class="clash-comments">')
        pieces.append('    <h3>Comments ({})</h3>'.format(len(comments)))
        for cm in comments:
            pieces.append(
                '    <div class="comment"><span class="cm-when mono">{}</span>'
                ' <span class="cm-author">{}</span><div class="cm-body">{}</div></div>'
                .format(_esc(_short_when(cm.get('at'))),
                        _esc(cm.get('author') or 'unknown'),
                        _esc(cm.get('body') or '')))
        pieces.append('  </div>')

    if history:
        pieces.append('  <div class="clash-history">')
        pieces.append('    <h3>History ({})</h3>'.format(len(history)))
        pieces.append('    <ul>')
        for h in history:
            pieces.append(
                '      <li><span class="h-when mono">{}</span>'
                ' <span class="h-author">{}</span> '
                '<span class="h-action">{}</span></li>'.format(
                    _esc(_short_when(h.get('at'))),
                    _esc(h.get('author') or 'unknown'),
                    _esc(_format_history_action(h))))
        pieces.append('    </ul>')
        pieces.append('  </div>')

    pieces.append('</article>')
    return '\n'.join(pieces) + '\n'


def _format_history_action(history_entry):
    action = history_entry.get('action') or ''
    before = history_entry.get('before')
    after = history_entry.get('after')
    if before is not None and after is not None:
        return '{}: {} → {}'.format(action, before, after)
    return action


def _short_when(iso_str):
    """Format an ISO timestamp as a short "YYYY-MM-DD HH:MM" string for
    display. Returns the raw input if it's not ISO-shaped (defensive)."""
    if not iso_str:
        return ''
    s = str(iso_str)
    if 'T' not in s:
        return s
    date_part, time_part = s.split('T', 1)
    if '.' in time_part:
        time_part = time_part.split('.', 1)[0]
    if time_part.endswith('Z'):
        time_part = time_part[:-1]
    return '{} {}'.format(date_part, time_part[:5])


# ---------------------------------------------------------------------------
# Thumbnails
# ---------------------------------------------------------------------------

def _read_thumbnail_data_uri(clash_id, viewpoints_dir):
    """Read the per-clash thumbnail PNG and return a `data:image/png;base64,...`
    URI suitable for inline `<img src=...>` use. Returns '' if missing or
    unreadable.
    """
    if not clash_id or not viewpoints_dir:
        return ''
    path = os.path.join(viewpoints_dir, '{}.png'.format(clash_id))
    if not os.path.isfile(path):
        return ''
    try:
        with open(path, 'rb') as f:
            data = f.read()
    except Exception:
        return ''
    encoded = base64.b64encode(data)
    if isinstance(encoded, bytes):
        encoded = encoded.decode('ascii')
    return 'data:image/png;base64,' + encoded


# ---------------------------------------------------------------------------
# Escaping
# ---------------------------------------------------------------------------

def _esc(s):
    """HTML-escape a value. Handles None, ints, etc. by str()-ing first.
    Avoids importing `html` (Python 3) or `cgi` (deprecated in Python 3)
    to stay portable across IronPython 2.7 and CPython 3.
    """
    return (str(s if s is not None else '')
            .replace('&', '&amp;')
            .replace('<', '&lt;')
            .replace('>', '&gt;')
            .replace('"', '&quot;')
            .replace("'", '&#39;'))


